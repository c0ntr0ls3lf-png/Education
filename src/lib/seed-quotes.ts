export async function seedQuotes() {
  await connectDB()
  const existing = await Quote.countDocuments()
  if (existing > 0) {
    console.log(`Quotes already seeded (${existing} found). Skipping.`)
    return
  }

  for (let i = 0; i < bengaliQuotes.length; i++) {
    const q = bengaliQuotes[i]
    await Quote.create({
      text: q.text,
      author: q.author,
      order: i,
      isActive: true,
    })
  }

  console.log(`Seeded ${bengaliQuotes.length} Bengali quotes.`)
}
